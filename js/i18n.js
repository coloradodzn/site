let i18nApplying = false;

function i18nApply(lang) {
  if (!I18N_SUPPORTED.includes(lang)) lang = I18N_DEFAULT;
  if (i18nApplying) return;
  i18nApplying = true;

  try {
    const dict = I18N[lang] || I18N[I18N_DEFAULT];
    document.documentElement.lang = lang;

    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const value = dict[el.getAttribute("data-i18n")];
      if (value != null) el.textContent = value;
    });

    // Solo stringhe nostre del dizionario (markup controllato: strong, em, br…)
    document.querySelectorAll("[data-i18n-html]").forEach((el) => {
      const value = dict[el.getAttribute("data-i18n-html")];
      if (value != null) el.innerHTML = value;
    });

    Object.keys(I18N_ATTR_MAP).forEach((dataAttr) => {
      document.querySelectorAll("[" + dataAttr + "]").forEach((el) => {
        const value = dict[el.getAttribute(dataAttr)];
        if (value != null) el.setAttribute(I18N_ATTR_MAP[dataAttr], value);
      });
    });

    document.querySelectorAll(".navbar__lang-btn").forEach((btn) => {
      const isActive = btn.getAttribute("data-lang") === lang;
      btn.classList.toggle("is-active", isActive);
      btn.setAttribute("aria-pressed", String(isActive));
    });

    try {
      localStorage.setItem(I18N_STORAGE_KEY, lang);
    } catch (err) {
      /* storage blocked */
    }

    window.dispatchEvent(new CustomEvent("colorado:langchange", { detail: { lang } }));
  } finally {
    i18nApplying = false;
  }
}

function coloradoRefreshI18n() {
  i18nApply(i18nDetectLang());
}

window.coloradoRefreshI18n = coloradoRefreshI18n;

function bootI18n() {
  i18nApply(i18nDetectLang());
}

if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", bootI18n);
} else {
  bootI18n();
}

/* Delegation: sopravvive alla navigazione SPA (body sostituito) */
document.addEventListener("click", (event) => {
  const btn = event.target.closest(".navbar__lang-btn");
  if (!btn) return;
  event.preventDefault();
  const lang = btn.getAttribute("data-lang");
  if (lang && I18N_SUPPORTED.includes(lang)) i18nApply(lang);
});

window.i18nApply = i18nApply;
window.i18nDetectLang = i18nDetectLang;
